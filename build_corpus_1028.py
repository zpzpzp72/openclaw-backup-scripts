import json, os

STAMP = '2026-10-28'
parts = []
parts.append('# Scout Corpus - ' + STAMP + '\n\n_Generated by NightOps-Scout cron. Raw evidence for graphify ingestion._\n')
parts.append('\n## Collection notes\n\n'
             '- Window: 2026-10-28 00:30-01:05 CST (Wed, NightOps window Mon-Fri 00:30-03:00)\n'
             '- Sources: arXiv API (cs.AI 60 / cs.MA 40 / MCP 40 / tool-agent 50 = 190 parsed), '
             'GitHub via authenticated gh CLI (19 repos releases + 9 repos commits + 2 advisories), '
             'HackerNews firebaseio top30, RSS (OpenAI 1326 / Vercel atom 1713 / Google AI 20 / '
             'Google News MCP-agent 90), Anthropic news HTML table extraction, openai/math raw markdown\n'
             '- web_search provider still failing (duckduckgo provider_error) - 10th consecutive run\n'
             '- web_fetch blocked on openai.com (private-IP resolution guard); direct curl also 403 (Cloudflare) '
             '- content recovered via RSS descriptions + raw.githubusercontent.com/openai/math\n')

for f, label in [('scout-raw/arxiv-csAI-parsed-1028.json', 'cs.AI'),
                 ('scout-raw/arxiv-csMA-parsed-1028.json', 'cs.MA'),
                 ('scout-raw/arxiv-mcp-parsed-1028.json', 'MCP'),
                 ('scout-raw/arxiv-toolagent-parsed-1028.json', 'tool-agent')]:
    if not os.path.exists(f):
        continue
    for x in json.load(open(f)):
        parts.append('\n## arXiv ' + x['id'][:12] + ' - ' + x['title'] + '\n\n'
                     '- categories: ' + ', '.join(x['cats'])
                     + '\n- published: ' + x['published']
                     + '\n- authors: ' + ', '.join(x['authors'][:5])
                     + '\n- query-set: ' + label + '\n\n' + x['summary'] + '\n')

REL = [('scout-raw/gh-1028-modelcontextprotocol-servers.json', 'MCP servers'),
       ('scout-raw/gh-1028-modelcontextprotocol-modelcontextprotocol.json', 'MCP spec'),
       ('scout-raw/gh-1028-modelcontextprotocol-registry.json', 'MCP registry'),
       ('scout-raw/gh-1028-modelcontextprotocol-inspector.json', 'MCP inspector'),
       ('scout-raw/gh-1028-modelcontextprotocol-python-sdk.json', 'MCP python-sdk'),
       ('scout-raw/gh-1028-modelcontextprotocol-typescript-sdk.json', 'MCP typescript-sdk'),
       ('scout-raw/gh-1028-modelcontextprotocol-go-sdk.json', 'MCP go-sdk'),
       ('scout-raw/gh-1028-modelcontextprotocol-swift-sdk.json', 'MCP swift-sdk'),
       ('scout-raw/gh-1028-modelcontextprotocol-csharp-sdk.json', 'MCP csharp-sdk'),
       ('scout-raw/gh-1028-modelcontextprotocol-ruby-sdk.json', 'MCP ruby-sdk'),
       ('scout-raw/gh-1028-modelcontextprotocol-rust-sdk.json', 'MCP rust-sdk'),
       ('scout-raw/gh-1028-modelcontextprotocol-java-sdk.json', 'MCP java-sdk'),
       ('scout-raw/gh-1028-modelcontextprotocol-kotlin-sdk.json', 'MCP kotlin-sdk'),
       ('scout-raw/gh-1028-modelcontextprotocol-php-sdk.json', 'MCP php-sdk'),
       ('scout-raw/gh-1028-modelcontextprotocol-ext-apps.json', 'MCP ext-apps'),
       ('scout-raw/gh-1028-anthropics-anthropic-sdk-python.json', 'anthropic-sdk-python'),
       ('scout-raw/gh-1028-anthropics-claude-code.json', 'claude-code')]
for f, label in REL:
    if not os.path.exists(f):
        continue
    d = json.load(open(f))
    if not isinstance(d, list):
        continue
    parts.append('\n## GitHub releases - ' + label + '\n')
    for r in d[:6]:
        body = ' '.join((r.get('body') or '').split())[:900]
        parts.append('- ' + str(r.get('tag_name')) + ' @ ' + str(r.get('published_at'))
                     + ' :: ' + body + '\n')

import glob
for f in sorted(glob.glob('scout-raw/gh-1028-commits-*.json')):
    label = f.replace('scout-raw/gh-1028-commits-modelcontextprotocol-', 'MCP ').replace('-', ' ').replace('.json', '')
    d = json.load(open(f))
    if not isinstance(d, list):
        continue
    parts.append('\n## Commits - ' + label + '\n')
    for c in d[:14]:
        try:
            parts.append('- ' + c['commit']['author']['date'] + ' :: '
                         + c['commit']['message'].split(chr(10))[0][:180] + '\n')
        except Exception:
            pass

for f, label in [('scout-raw/gh-1028-advisories-servers.json', 'MCP servers'),
                 ('scout-raw/gh-1028-advisories-registry.json', 'MCP registry')]:
    if not os.path.exists(f):
        continue
    parts.append('\n## Security advisories - ' + label + '\n')
    for a in json.load(open(f)):
        parts.append('- ' + str(a.get('ghsa_id')) + ' | ' + str(a.get('severity'))
                     + ' | ' + str(a.get('published_at')) + ' | ' + str(a.get('summary'))[:160] + '\n')

if os.path.exists('scout-raw/hn-1028.json'):
    parts.append('\n## HackerNews top30\n')
    for x in json.load(open('scout-raw/hn-1028.json')):
        parts.append('- ' + str(x['score']) + ' pts / ' + str(x['comments']) + ' c :: '
                     + x['title'] + ' :: ' + x['url'] + '\n')

RSS = [('scout-raw/rss-openai-1028.xml', 'OpenAI'),
       ('scout-raw/rss-vercel-1028.xml', 'Vercel'),
       ('scout-raw/rss-gai-1028.xml', 'Google AI')]
import xml.etree.ElementTree as ET
for f, label in RSS:
    if not os.path.exists(f):
        continue
    parts.append('\n## RSS - ' + label + '\n')
    try:
        root = ET.parse(f).getroot()
    except Exception:
        continue
    items = root.findall('.//item')
    if items:
        for it in items[:15]:
            t = it.find('title')
            p = it.find('pubDate')
            l = it.find('link')
            d = it.find('description')
            parts.append('- ' + (p.text[:25] if p is not None and p.text else '')
                         + ' | ' + (''.join(t.itertext())[:110] if t is not None else '')
                         + ' | ' + (l.text if l is not None and l.text else '')
                         + ' | ' + (' '.join(''.join(d.itertext()).split())[:220] if d is not None else '')
                         + '\n')
    else:
        ns = {'a': 'http://www.w3.org/2005/Atom'}
        for e in root.findall('a:entry', ns)[:20]:
            ti = e.find('a:title', ns)
            up = e.find('a:updated', ns)
            l = e.find('a:link', ns)
            parts.append('- ' + (up.text[:25] if up is not None and up.text else '')
                         + ' | ' + (''.join(ti.itertext())[:110] if ti is not None else '')
                         + ' | ' + (l.get('href') if l is not None else '') + '\n')

if os.path.exists('scout-raw/gnews-1028.xml'):
    parts.append('\n## Google News - MCP / AI agent\n')
    try:
        for it in ET.parse('scout-raw/gnews-1028.xml').getroot().findall('.//item')[:30]:
            ti = it.find('title')
            pd = it.find('pubDate')
            parts.append('- ' + (pd.text[:25] if pd is not None and pd.text else '')
                         + ' | ' + (ti.text[:130] if ti is not None else '') + '\n')
    except Exception:
        pass

