import json, os
os.makedirs('graphify-out/raw', exist_ok=True)
stamp = '2026-10-24'
parts = []
parts.append('# Scout Corpus - ' + stamp + '\n\n_Generated by NightOps-Scout cron. Raw evidence for graphify ingestion._\n')
for f, label in [('scout-raw/arxiv-csAI-parsed.json','cs.AI'),('scout-raw/arxiv-mcpexact-parsed.json','MCP'),('scout-raw/arxiv-toolagent-parsed.json','tool-agent')]:
    if not os.path.exists(f): continue
    for x in json.load(open(f)):
        parts.append('\n## arXiv ' + x['id'][:12] + ' - ' + x['title'] + '\n\n- categories: ' + ', '.join(x['cats']) + '\n- published: ' + x['published'] + '\n- authors: ' + ', '.join(x['authors'][:5]) + '\n- query-set: ' + label + '\n\n' + x['summary'] + '\n')
for f, label in [('scout-raw/gh-mcp-spec-releases.json','MCP spec'),('scout-raw/gh-mcp-servers-releases.json','MCP servers'),('scout-raw/gh-mcp-inspector-releases.json','MCP inspector'),('scout-raw/gh-anthropic-sdk-py.json','anthropic-sdk-python'),('scout-raw/gh-modelcontextprotocol-python-sdk.json','MCP python-sdk'),('scout-raw/github-mcp-ts.json','MCP typescript-sdk'),('scout-raw/github-mcp-rust.json','MCP rust-sdk'),('scout-raw/github-mcp-csharp.json','MCP csharp-sdk'),('scout-raw/github-mcp-go.json','MCP go-sdk'),('scout-raw/gh-claude-code-releases.json','claude-code')]:
    if not os.path.exists(f): continue
    d = json.load(open(f))
    if not isinstance(d, list): continue
    parts.append('\n## GitHub releases - ' + label + '\n')
    for r in d[:6]:
        parts.append('- ' + str(r.get('tag_name')) + ' @ ' + str(r.get('published_at')) + '\n')
for f, label in [('scout-raw/gh-spec-commits.json','MCP spec'),('scout-raw/gh-servers-commits.json','MCP servers'),('scout-raw/github-mcp-registry.json','MCP registry'),('scout-raw/gh-extauth-commits.json','MCP ext-auth'),('scout-raw/gh-extapps-commits.json','MCP ext-apps'),('scout-raw/gh-claude-code-commits.json','claude-code')]:
    if not os.path.exists(f): continue
    d = json.load(open(f))
    if not isinstance(d, list): continue
    parts.append('\n## Commits - ' + label + '\n')
    for c in d[:8]:
        try:
            parts.append('- ' + c['commit']['author']['date'] + ' ' + c['commit']['message'].split('\n')[0] + '\n')
        except Exception: pass
news = open('scout-raw/news-block.txt').read() if os.path.exists('scout-raw/news-block.txt') else ''
parts.append('\n## Industry news - 2026-10-23 / 10-22\n\n' + news + '\n')
body = ''.join(parts)
out = 'graphify-out/raw/scout-' + stamp + '-corpus.md'
open(out, 'w').write(body)
print('wrote', out, len(body), 'chars, arxiv sections:', body.count('## arXiv'))
