import json, os, glob

STAMP = '2026-10-26'
parts = []
parts.append('# Scout Corpus - ' + STAMP + '\n\n_Generated by NightOps-Scout cron. Raw evidence for graphify ingestion._\n')

for f, label in [('scout-raw/arxiv-csAI-parsed.json', 'cs.AI'),
                 ('scout-raw/arxiv-csMA-parsed.json', 'cs.MA'),
                 ('scout-raw/arxiv-mcpexact-parsed.json', 'MCP'),
                 ('scout-raw/arxiv-toolagent-parsed.json', 'tool-agent')]:
    if not os.path.exists(f):
        continue
    for x in json.load(open(f)):
        parts.append('\n## arXiv ' + x['id'][:12] + ' - ' + x['title'] + '\n\n'
                     '- categories: ' + ', '.join(x['cats'])
                     + '\n- published: ' + x['published']
                     + '\n- authors: ' + ', '.join(x['authors'][:5])
                     + '\n- query-set: ' + label + '\n\n' + x['summary'] + '\n')

for f, label in [('scout-raw/gh-mcp-spec-releases.json', 'MCP spec'),
                 ('scout-raw/gh-mcp-servers-releases.json', 'MCP servers'),
                 ('scout-raw/gh-mcp-inspector-releases.json', 'MCP inspector'),
                 ('scout-raw/gh-anthropic-sdk-py.json', 'anthropic-sdk-python'),
                 ('scout-raw/gh-modelcontextprotocol-python-sdk.json', 'MCP python-sdk'),
                 ('scout-raw/github-mcp-ts.json', 'MCP typescript-sdk'),
                 ('scout-raw/github-mcp-rust.json', 'MCP rust-sdk'),
                 ('scout-raw/github-mcp-csharp.json', 'MCP csharp-sdk'),
                 ('scout-raw/github-mcp-go.json', 'MCP go-sdk'),
                 ('scout-raw/gh-claude-code-releases.json', 'claude-code')]:
    if not os.path.exists(f):
        continue
    d = json.load(open(f))
    if not isinstance(d, list):
        continue
    parts.append('\n## GitHub releases - ' + label + '\n')
    for r in d[:6]:
        parts.append('- ' + str(r.get('tag_name')) + ' @ ' + str(r.get('published_at')) + '\n')

for f, label in [('scout-raw/gh-spec-commits.json', 'MCP spec'),
                 ('scout-raw/gh-servers-commits.json', 'MCP servers'),
                 ('scout-raw/github-mcp-registry.json', 'MCP registry'),
                 ('scout-raw/gh-extauth-commits.json', 'MCP ext-auth'),
                 ('scout-raw/gh-extapps-commits.json', 'MCP ext-apps'),
                 ('scout-raw/gh-commits-modelcontextprotocol-python-sdk.json', 'MCP python-sdk'),
                 ('scout-raw/gh-commits-modelcontextprotocol-typescript-sdk.json', 'MCP typescript-sdk'),
                 ('scout-raw/gh-commits-modelcontextprotocol-swift-sdk.json', 'MCP swift-sdk'),
                 ('scout-raw/gh-commits-modelcontextprotocol-ruby-sdk.json', 'MCP ruby-sdk'),
                 ('scout-raw/gh-commits-modelcontextprotocol-csharp-sdk.json', 'MCP csharp-sdk'),
                 ('scout-raw/gh-commits-modelcontextprotocol-go-sdk.json', 'MCP go-sdk'),
                 ('scout-raw/gh-commits-modelcontextprotocol-inspector.json', 'MCP inspector'),
                 ('scout-raw/gh-commits-modelcontextprotocol-governance-wg.json', 'MCP governance-wg'),
                 ('scout-raw/gh-commits-modelcontextprotocol-access.json', 'MCP access')]:
    if not os.path.exists(f):
        continue
    d = json.load(open(f))
    if not isinstance(d, list):
        continue
    parts.append('\n## Commits - ' + label + '\n')
    for c in d[:10]:
        try:
            parts.append('- ' + c['commit']['author']['date'] + ' ' + c['commit']['message'].split('\n')[0] + '\n')
        except Exception:
            pass

if os.path.exists('scout-raw/gh-mcp-advisories.json'):
    parts.append('\n## GitHub Security Advisories - modelcontextprotocol/servers\n')
    for a in json.load(open('scout-raw/gh-mcp-advisories.json'))[:12]:
        parts.append('- ' + str(a.get('ghsa_id')) + ' [' + str(a.get('severity')) + '] '
                     + str(a.get('published_at')) + ' ' + str(a.get('summary')) + '\n')

if os.path.exists('scout-raw/hn-items.json'):
    parts.append('\n## Hacker News top 30 (2026-10-25)\n')
    for i in json.load(open('scout-raw/hn-items.json'))[:30]:
        parts.append('- [' + str(i.get('score')) + ' pts / ' + str(i.get('descendants', 0)) + ' comments] '
                     + i.get('title', '') + ' — ' + (i.get('url') or '') + '\n')

if os.path.exists('scout-raw/news-block.txt'):
    parts.append('\n## Industry news - 2026-10-23 / 10-22 / 10-25\n\n'
                 + open('scout-raw/news-block.txt').read() + '\n')

body = ''.join(parts)
out = 'graphify-out/raw/scout-' + STAMP + '-corpus.md'
open(out, 'w').write(body)
print('wrote', out, len(body), 'chars, arxiv sections:', body.count('## arXiv'))
