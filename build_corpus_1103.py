def extract_text(f, limit=4000):
    if not os.path.exists(f):
        return ''
    t = open(f, encoding='utf-8', errors='ignore').read()
    t2 = re.sub(r'<script.*?</script>|<style.*?</style>', '', t, flags=re.S)
    txt = ' '.join(re.sub('<.*?>', ' ', html.unescape(t2)).split())
    return txt[:limit]


